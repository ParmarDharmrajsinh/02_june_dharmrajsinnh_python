# 2) Write a Python program to read a string, an integer, and a float from the keyboard and display them.

text = input("Enter a string: ")
integer_number = int(input("Enter an integer: "))
float_number = float(input("Enter a float: "))

print("\nYou entered:")
print(f"String: {text}")
print(f"Integer: {integer_number}")
print(f"Float: {float_number}")
